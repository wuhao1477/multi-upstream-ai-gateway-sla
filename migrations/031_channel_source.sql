-- 031：channels 补 source —— 这个渠道是**谁建的**
--
-- 为什么需要它：all-api-hub 定时同步要能把"备份里已经移除的渠道"自动停用
-- （2026-09-16 需求）。而"不在备份里"有两种完全不同的含义：
--
--   · 它本来就是 hub 建的，现在备份里没了  → 人在扩展那边删掉了，该停用
--   · 它是运维在本界面手工建的             → 备份里从来就没有过它
--
-- 两者在数据上长得一模一样（都是"base_url 不在这份备份里"），而把后者也停掉
-- 是个反复发作的坑：定时同步每轮都会把手工加的渠道再关一次，人每次重新启用，
-- 下一轮又被关。没有这一列就只能在"漏停"和"误停"之间二选一。
--
-- 默认 'manual'：已有的渠道里分不清来源的一律当手工建的 —— **保守的那一边**。
-- 误判成 manual 的后果是"该停的没停"（人自己看得见、可手动停），
-- 误判成 hub 的后果是"不该停的被停了"，而那是个会重复发作的惊吓。
-- 下一次 hub 导入碰到同地址的渠道时会把它改成 'hub'（见 import_api.go），
-- 所以这个默认值只在"从未被 hub 同步碰过"的渠道上停留。

ALTER TABLE channels
  ADD COLUMN source TEXT NOT NULL DEFAULT 'manual'
    CHECK (source IN ('manual', 'hub'));

COMMENT ON COLUMN channels.source IS
  '渠道来源：manual=界面手工建；hub=all-api-hub 导入/同步建或接管。定时同步只对 hub 的做"备份里已移除即停用"。';
